// Generates web/src/demo/abis.generated.ts from contracts/out/*.json (ADR-0016, ROADMAP 6.2).
// Demo mode needs ABIs in static/CI builds where `src/generated/deployments` is empty, so the
// output IS committed. Regenerate after any contract ABI change:
//   node web/scripts/gen-demo-abis.mjs          # write
//   node web/scripts/gen-demo-abis.mjs --check  # exit 1 if the committed file has drifted
// Needs `contracts/out` (`cd contracts && uv run mox compile`).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const outDir = fileURLToPath(new URL('../../contracts/out/', import.meta.url));
const target = fileURLToPath(new URL('../src/demo/abis.generated.ts', import.meta.url));

/** Demo contract key → compiled artifact name. MockUSDC stands in for USDC. */
const SOURCES = [
  ['AdSlot', 'AdSlot'],
  ['Marketplace', 'Marketplace'],
  ['CreativeRegistry', 'CreativeRegistry'],
  ['CampaignVault', 'CampaignVault'],
  ['USDC', 'MockUSDC'],
];

const KEPT_TYPES = new Set(['function', 'event', 'error']);

/** Recursively sorts object keys so the output is byte-stable across compiler JSON orderings. */
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sortKeys(value[k])]),
    );
  }
  return value;
}

function render() {
  const abis = {};
  for (const [key, artifact] of SOURCES) {
    const file = `${outDir}${artifact}.json`;
    if (!existsSync(file)) {
      console.error(`gen-demo-abis: missing ${file} — run \`cd contracts && uv run mox compile\`.`);
      process.exit(1);
    }
    const parsed = JSON.parse(readFileSync(file, 'utf8'));
    abis[key] = parsed.abi.filter((entry) => KEPT_TYPES.has(entry.type)).map(sortKeys);
  }
  return [
    '// GENERATED by web/scripts/gen-demo-abis.mjs from contracts/out — do commit; regenerate after',
    '// contract ABI changes (`node web/scripts/gen-demo-abis.mjs`). CI runs it with `--check`.',
    '// Demo mode only (ADR-0016): never imported outside `web/src/demo/`.',
    `export const DEMO_ABIS = ${JSON.stringify(abis, null, 2)} as const;`,
    '',
  ].join('\n');
}

const next = render();
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== next) {
    console.error('gen-demo-abis: web/src/demo/abis.generated.ts is out of date — run `node web/scripts/gen-demo-abis.mjs`.');
    process.exit(1);
  }
  console.log('gen-demo-abis: up to date.');
} else {
  writeFileSync(target, next);
  console.log('gen-demo-abis: wrote web/src/demo/abis.generated.ts');
}
