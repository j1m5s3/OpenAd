// Copies contracts/deployments/<chainId>.json into web/src/generated/deployments/ and writes a
// typed index. Runs before dev/typecheck/build. The generated folder is git-ignored.
// Schema: docs/ARCHITECTURE.md §4.1. Consumer: src/lib/deployments.ts.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const sourceDir = fileURLToPath(new URL('../../contracts/deployments/', import.meta.url));
const outDir = fileURLToPath(new URL('../src/generated/deployments/', import.meta.url));

mkdirSync(outDir, { recursive: true });

const files = existsSync(sourceDir)
  ? readdirSync(sourceDir)
      .filter((f) => /^\d+\.json$/.test(f))
      .sort()
  : [];

const imports = [];
const entries = [];
for (const file of files) {
  const chainId = file.replace(/\.json$/, '');
  const raw = readFileSync(`${sourceDir}${file}`, 'utf8');
  const parsed = JSON.parse(raw);
  if (parsed.artifactVersion !== 1 || String(parsed.chainId) !== chainId) {
    throw new Error(`sync-deployments: ${file} is malformed (artifactVersion/chainId)`);
  }
  writeFileSync(`${outDir}${file}`, raw);
  imports.push(`import d${chainId} from './${file}';`);
  entries.push(`  ${chainId}: d${chainId} as unknown as DeploymentsArtifact,`);
}

const index = [
  '// GENERATED by scripts/sync-deployments.mjs — do not edit, do not commit.',
  "import type { DeploymentsArtifact } from '../../lib/deployments';",
  ...imports,
  '',
  'export const deployments: Record<number, DeploymentsArtifact> = {',
  ...entries,
  '};',
  '',
].join('\n');

writeFileSync(`${outDir}index.ts`, index);
console.log(`sync-deployments: ${files.length} artifact(s) → src/generated/deployments/`);
